export function classifyJobRegion(locations: readonly string[]): JobRegionDecision {
  const text = locations.join(' ').trim().toLocaleLowerCase();
  if (!text) return 'unknown';
  if (foreignTerms.some((term) => text.includes(term.toLocaleLowerCase()))) return 'non_domestic';
  if (domesticTerms.some((term) => text.includes(term))) return 'domestic';
  return 'unknown';
}
